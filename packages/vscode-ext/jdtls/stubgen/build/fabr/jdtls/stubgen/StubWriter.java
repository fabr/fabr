package build.fabr.jdtls.stubgen;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;
import org.objectweb.asm.Opcodes;
import org.objectweb.asm.signature.SignatureReader;
import org.objectweb.asm.tree.ClassNode;
import org.objectweb.asm.tree.FieldNode;
import org.objectweb.asm.tree.MethodNode;
import org.objectweb.asm.util.TraceSignatureVisitor;

/** Renders a stub as Java source. */
final class StubWriter {
    /**
     * A library class to stub: its real class, the supertypes the stub keeps (the superclass
     * first, where it keeps one) and the members it holds.
     */
    record Stub(ClassNode node, List<String> supertypes, Set<FieldNode> fields, Set<MethodNode> methods) {
    }

    private static final String HEADER = """
        /*
         * Copyright (c) 2026 Nathan Keynes <nkeynes@deadcoderemoval.net>
         *
         * This file is part of Fabr.
         *
         * Fabr is free software: you can redistribute it and/or modify it under the
         * terms of the GNU General Public License as published by the Free Software
         * Foundation, either version 3 of the License, or (at your option) any later
         * version.
         *
         * Fabr is distributed in the hope that it will be useful, but WITHOUT ANY
         * WARRANTY; without even the implied warranty of MERCHANTABILITY or FITNESS
         * FOR A PARTICULAR PURPOSE. See the GNU General Public License for more
         * details.
         */
        """;

    private static final String BODY = " {\n        throw new UnsupportedOperationException();\n    }\n";

    private StubWriter() {
    }

    /** Render `stub` as a source file; `stubs` are every stub, by internal name. */
    static String render(Stub stub, Map<String, Stub> stubs) {
        ClassNode node = stub.node();
        boolean isInterface = (node.access & Opcodes.ACC_INTERFACE) != 0;
        int slash = node.name.lastIndexOf('/');
        String simpleName = node.name.substring(slash + 1);
        StringBuilder out = new StringBuilder(HEADER);
        out.append("\npackage ").append(node.name.substring(0, slash).replace('/', '.')).append(";\n\n");
        out.append("/** Generated by jdtls_stubgen: a stub of the language server's class, holding the members fabr's importer uses. */\n");
        out.append(visibility(node.access));
        if (isInterface) {
            out.append("interface ");
        } else {
            out.append((node.access & Opcodes.ACC_ABSTRACT) != 0 ? "abstract " : "")
               .append((node.access & Opcodes.ACC_FINAL) != 0 ? "final " : "")
               .append("class ");
        }
        out.append(simpleName).append(classHeader(stub, isInterface)).append(" {\n");

        List<String> members = new ArrayList<>();
        for (FieldNode field : node.fields) {
            if (stub.fields().contains(field)) {
                members.add(renderField(field, isInterface));
            }
        }
        boolean constructors = false;
        for (MethodNode method : node.methods) {
            if (stub.methods().contains(method)) {
                constructors |= method.name.equals("<init>");
                members.add(renderMethod(method, simpleName, isInterface));
            }
        }
        if (!isInterface && !constructors) {
            /* The real class's constructors are not the code's to call; a stub extending this one still calls one. */
            boolean extended = stubs.values().stream().anyMatch(other -> !other.supertypes().isEmpty() && other.supertypes().get(0).equals(node.name));
            members.add(0, "    " + (extended ? "protected " : "private ") + simpleName + "()" + BODY);
        }
        out.append(String.join("\n", members)).append("}\n");
        return out.toString();
    }

    /** @return the type parameters, superclass and interfaces of `stub`'s declaration. */
    private static String classHeader(Stub stub, boolean isInterface) {
        ClassNode node = stub.node();
        List<String> kept = stub.supertypes();
        String typeParameters = "";
        String superclass = null;
        List<String> interfaces = new ArrayList<>();
        if (node.signature != null) {
            TraceSignatureVisitor visitor = new TraceSignatureVisitor(node.access);
            new SignatureReader(node.signature).accept(visitor);
            String declaration = visitor.getDeclaration();
            if (declaration.startsWith("<")) {
                int end = matching(declaration, 0);
                typeParameters = declaration.substring(0, end + 1);
                declaration = declaration.substring(end + 1);
            }
            /* Supertypes as the signature renders them, generic arguments included, kept where the stub keeps the type. */
            List<String> rendered = new ArrayList<>();
            for (String part : declaration.replaceFirst("^ extends ", "").split(" implements ", 2)) {
                rendered.addAll(splitTopLevel(part));
            }
            List<String> real = new ArrayList<>();
            if (!isInterface) {
                real.add(node.superName);
            }
            real.addAll(node.interfaces);
            for (int i = 0; i < real.size() && i < rendered.size(); i++) {
                if (kept.contains(real.get(i))) {
                    if (i == 0 && !isInterface) {
                        superclass = javaType(rendered.get(i));
                    } else {
                        interfaces.add(javaType(rendered.get(i)));
                    }
                }
            }
        } else {
            for (String type : kept) {
                if (!isInterface && type.equals(node.superName)) {
                    superclass = type.replace('/', '.');
                } else {
                    interfaces.add(javaType(type.replace('/', '.')));
                }
            }
        }
        StringBuilder header = new StringBuilder(typeParameters);
        if (superclass != null && !superclass.equals("java.lang.Object")) {
            header.append(" extends ").append(superclass);
        }
        if (!interfaces.isEmpty()) {
            header.append(isInterface ? " extends " : " implements ").append(String.join(", ", interfaces));
        }
        return header.toString();
    }

    private static String renderField(FieldNode field, boolean isInterface) {
        TraceSignatureVisitor visitor = new TraceSignatureVisitor(0);
        new SignatureReader(field.signature != null ? field.signature : field.desc).acceptType(visitor);
        boolean constant = (field.access & Opcodes.ACC_STATIC) != 0 && (field.access & Opcodes.ACC_FINAL) != 0 && field.value != null;
        StringBuilder out = new StringBuilder("    ");
        if (!isInterface) {
            out.append(visibility(field.access)).append((field.access & Opcodes.ACC_STATIC) != 0 ? "static " : "").append(constant ? "final " : "");
        }
        out.append(javaType(visitor.getDeclaration())).append(' ').append(field.name);
        if (constant) {
            out.append(" = ").append(literal(field.value, field.desc));
        } else if (isInterface) {
            throw new IllegalStateException("cannot stub " + field.name + ": an interface field that is not a constant");
        }
        return out.append(";\n").toString();
    }

    private static String renderMethod(MethodNode method, String simpleName, boolean isInterface) {
        TraceSignatureVisitor visitor = new TraceSignatureVisitor(method.access);
        new SignatureReader(method.signature != null ? method.signature : method.desc).accept(visitor);
        String declaration = visitor.getDeclaration();
        String typeParameters = "";
        if (declaration.startsWith("<")) {
            int end = matching(declaration, 0);
            typeParameters = declaration.substring(0, end + 1) + " ";
            declaration = declaration.substring(end + 1);
        }
        List<String> parameterTypes = splitTopLevel(declaration.substring(1, declaration.length() - 1));
        List<String> parameters = new ArrayList<>();
        for (int i = 0; i < parameterTypes.size(); i++) {
            String type = javaType(parameterTypes.get(i));
            if (i == parameterTypes.size() - 1 && (method.access & Opcodes.ACC_VARARGS) != 0) {
                type = type.substring(0, type.length() - 2) + "...";
            }
            parameters.add(type + " arg" + i);
        }
        boolean isAbstract = (method.access & Opcodes.ACC_ABSTRACT) != 0;
        boolean isStatic = (method.access & Opcodes.ACC_STATIC) != 0;
        StringBuilder out = new StringBuilder("    ");
        if (isInterface) {
            out.append(isStatic ? "static " : isAbstract ? "" : "default ");
        } else {
            out.append(visibility(method.access)).append(isStatic ? "static " : "").append(isAbstract ? "abstract " : "")
               .append((method.access & Opcodes.ACC_FINAL) != 0 ? "final " : "");
        }
        out.append(typeParameters);
        if (method.name.equals("<init>")) {
            out.append(simpleName);
        } else {
            out.append(javaType(visitor.getReturnType())).append(' ').append(method.name);
        }
        out.append('(').append(String.join(", ", parameters)).append(')');
        if (method.exceptions != null && !method.exceptions.isEmpty()) {
            out.append(" throws ").append(String.join(", ", method.exceptions.stream().map(e -> javaType(e.replace('/', '.'))).toList()));
        }
        return out.append(isAbstract ? ";\n" : BODY).toString();
    }

    private static String visibility(int access) {
        if ((access & Opcodes.ACC_PUBLIC) != 0) {
            return "public ";
        }
        if ((access & Opcodes.ACC_PROTECTED) != 0) {
            return "protected ";
        }
        return (access & Opcodes.ACC_PRIVATE) != 0 ? "private " : "";
    }

    /** @return `type` as Java source names it: a nested class's binary name `Outer$Inner` as `Outer.Inner`. */
    private static String javaType(String type) {
        return type.replaceAll("\\$(?=[A-Za-z_])", ".");
    }

    /** @return the constant `value` of a field of descriptor `desc` as a Java literal. */
    private static String literal(Object value, String desc) {
        return switch (desc) {
            case "Z" -> ((Integer) value) != 0 ? "true" : "false";
            case "C" -> "(char) " + value;
            case "B" -> "(byte) " + value;
            case "S" -> "(short) " + value;
            case "J" -> value + "L";
            case "F" -> value + "f";
            case "D" -> value + "d";
            case "Ljava/lang/String;" -> quoted((String) value);
            default -> value.toString();
        };
    }

    private static String quoted(String text) {
        StringBuilder out = new StringBuilder("\"");
        for (char c : text.toCharArray()) {
            switch (c) {
                case '"' -> out.append("\\\"");
                case '\\' -> out.append("\\\\");
                case '\n' -> out.append("\\n");
                case '\r' -> out.append("\\r");
                case '\t' -> out.append("\\t");
                default -> {
                    if (c < 0x20 || c > 0x7e) {
                        out.append(String.format("\\u%04x", (int) c));
                    } else {
                        out.append(c);
                    }
                }
            }
        }
        return out.append('"').toString();
    }

    /** @return the index of the `>` closing the `<` at `start` of `text`. */
    private static int matching(String text, int start) {
        int depth = 0;
        for (int i = start; i < text.length(); i++) {
            char c = text.charAt(i);
            if (c == '<') {
                depth++;
            } else if (c == '>' && --depth == 0) {
                return i;
            }
        }
        throw new IllegalStateException("unbalanced type parameters in " + text);
    }

    /** @return the comma-separated parts of `text` outside any `<>`, trimmed. */
    private static List<String> splitTopLevel(String text) {
        List<String> parts = new ArrayList<>();
        int depth = 0;
        int from = 0;
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            if (c == '<') {
                depth++;
            } else if (c == '>') {
                depth--;
            } else if (c == ',' && depth == 0) {
                parts.add(text.substring(from, i).trim());
                from = i + 1;
            }
        }
        if (!text.isBlank()) {
            parts.add(text.substring(from).trim());
        }
        return parts;
    }
}
