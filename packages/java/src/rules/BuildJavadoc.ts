/**
 * The javadoc rule: the javadoc of the `.java` files among its `srcs`,
 * generated by `JAVADOC` against the classpath its `deps` make (the module
 * path, for sources that are a named module), for the release
 * {@link javaRelease} chooses. Its other files are on javadoc's source path,
 * where it reads a package's `package.html` and copies its `doc-files`. With
 * no `.java` files it yields nothing.
 */

import * as path from "path";
import {
  Computable,
  createExecAction,
  defineRule,
  EMPTY_FILESET,
  FileSet,
  IFile,
  MemoryFile,
  RuleResult,
  TargetContext,
  TREE_MOUNT,
} from "@fabr-build/core";
import { classpathOf, javaRelease, pathOption, placedJars, quotedArgument, stagedJars } from "../JarPackage";

/** The `javadoc` rule. */
export default defineRule({
  requirements(context) {
    return {
      srcs: context.getFileProperty("srcs"),
      deps: context.getPackageProperty("deps"),
    };
  },
  evaluateMaterialized(context, inputs) {
    return generateJavadoc(context, inputs);
  },
});

/** Where the sources are staged. */
const SOURCE_DIR = "src";
/** Where the classpath's jars are staged. */
const CLASSPATH_DIR = ".classpath";
/** Where javadoc writes the documentation. */
const DOC_DIR = "doc";
/** The argument file javadoc reads its arguments from. */
const ARGUMENTS_FILE = ".fabr-javadoc.args";

function generateJavadoc(context: TargetContext, { srcs, deps }: { srcs: FileSet[]; deps: FileSet[] }): Computable<RuleResult> {
  const sources = FileSet.unionAll(...srcs);
  const javaFiles = [...sources].map(([name]) => name).filter(name => name.endsWith(".java"));
  if (javaFiles.length === 0) {
    return Computable.resolve(EMPTY_FILESET);
  }
  const jars = classpathOf(deps);
  return Computable.forAll(
    [context.getGlobalString("JVM_TARGET"), context.getGlobalRunnable("JAVADOC"), placedJars(sources, jars)],
    (jvmTarget, javadoc, { modulePath, classpath }) => {
      const release = javaRelease(jvmTarget, deps);
      const pool = context.execution.buildCache;
      return pool.ensureTree(javadoc).then(() => {
        const argumentsText = [
          "--release",
          String(release),
          "-encoding",
          "UTF-8",
          "-docencoding",
          "UTF-8",
          "-charset",
          "UTF-8",
          "-quiet",
          "-d",
          DOC_DIR,
          "--source-path",
          SOURCE_DIR,
          ...pathOption("--module-path", CLASSPATH_DIR, modulePath),
          ...pathOption("-classpath", CLASSPATH_DIR, classpath),
          ...javaFiles.map(name => path.posix.join(SOURCE_DIR, name)).sort(),
        ]
          .map(quotedArgument)
          .join("\n");
        const files = FileSet.unionAll(
          sources.mountedAt(SOURCE_DIR),
          stagedJars(CLASSPATH_DIR, jars),
          new FileSet(new Map<string, IFile>([[ARGUMENTS_FILE, MemoryFile.from(argumentsText)], [TREE_MOUNT, pool.treePoolLink]]))
        );
        const argv = javadoc.toCommandLine([`@${ARGUMENTS_FILE}`], { base: path.posix.join(TREE_MOUNT, javadoc.toManifestHash()) });
        return createExecAction(files, argv, `${DOC_DIR}:**`);
      });
    }
  );
}
