import * as fs from "fs";
import * as os from "os";
import * as path from "path";

/** Write `files` (relative path -> contents; an object is written as JSON) under a fresh temporary directory.
 * @return the directory. */
export function writeProject(files: Record<string, string | object>): string {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "fabr-migrate-"));
  for (const [name, contents] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(root, name)), { recursive: true });
    fs.writeFileSync(path.join(root, name), typeof contents === "string" ? contents : JSON.stringify(contents));
  }
  return root;
}
