/**
 * A step's package graph written as a Yarn PnP manifest (`.pnp.data.json`):
 * each package's files are a tree of the cache's pool, and its row says where
 * that tree is and what each name it imports resolves to. js-tools'
 * PnpResolver reads the manifest for every driver (tsc, bundle, sass,
 * postcss). The table locates a package's directory; the files within it
 * (`main`, `types`, extensions) are found on disk.
 */

import {
  Computable,
  FabrError,
  FileSet,
  hashString,
  mapComputable,
  MemoryFile,
  nodeNaming,
  PACKAGE_RESOLUTION_PROVENANCE,
  PackageFileSet,
  packageNameConflict,
  packageNodeSignature,
  reachablePackages,
  readJsonFile,
  toJsonObject,
  toleratingFailure,
  TREE_MOUNT,
} from "@fabr-build/core";
import { type IPnpPackageInfo, type IPnpSerializedState, type PnpDependencyTarget, virtualLocation } from "@fabr-build/js-tools";

/** The package identity of the sources a step stages: the name they may
 * import themselves by, and where they are staged (a directory relative to the
 * manifest, `./src/`). */
export interface ISelfPackage {
  readonly name: string;
  readonly location: string;
}

/** The self row's reference: a fixed label, which cannot collide with a
 * package's reference (a hex digest). */
const SELF_REFERENCE = "self";

/** Where a manifest locates its packages, relative to the table's directory. */
export interface IPnpPlacement {
  /** The directory the trees lie in, each at `<pool>/<its content hash>`:
   *  the tree pool's link beside a staged step ({@link TREE_MOUNT}) by default. */
  readonly pool?: string;
  /** True to lay each direct package beside the table, at
   *  `node_modules/<name>/`, instead of in the pool, and an unplugged one with
   *  the unplugged tree it lies in, whose `node_modules` is then the table's
   *  own; otherwise false. */
  readonly besideTable?: boolean;
}

/** A manifest and the packages it has rows for. The caller must put each of
 * its {@link trees} in the pool before anything reads the manifest. */
export interface IPnpManifest {
  readonly state: IPnpSerializedState;
  /** Every package with a row, one instance per row. */
  readonly packages: ReadonlyArray<PackageFileSet>;
  /** The trees the rows are located in: each package's own, and the trees
   *  the unplugged packages lie in ({@link unpluggedTreesOf}), each at
   *  `<pool>/<its content hash>`. */
  readonly trees: ReadonlyArray<FileSet>;
  /** What lies beside the table, at the table's directory
   *  ({@link IPnpPlacement.besideTable}); empty where nothing does. */
  readonly beside: FileSet;
  /** Locate a package's row, relative to the working directory: its tree
   * ({@link treeMountOf}, or under the placement's pool), its directory in an
   * unplugged tree, or its directory beside the table, or, where
   * its content is wired more than one way in this manifest, the virtual
   * location of its wiring over that directory. */
  mountOf(pkg: PackageFileSet): string;
  /** Make the manifest the file to stage. */
  toFile(): MemoryFile;
}

const INFO = [
  "This file is generated by fabr. It maps every package this build resolved to",
  "its content-addressed directory in the build cache's tree pool.",
];

/**
 * Refuse two different packages of one name among `directDeps`: the sources
 * import a direct dependency by its name, so only one of them could be
 * imported.
 *
 * @throws the conflict between the first two ({@link packageNameConflict}). A
 *   rule calls this before yielding its action, so a cache hit cannot hide it.
 */
export function assertOnePackagePerName(directDeps: ReadonlyArray<FileSet>): void {
  const top = new Map<string, PackageFileSet>();
  for (const dep of directDeps) {
    if (dep instanceof PackageFileSet) {
      const held = top.get(dep.packageName);
      if (held !== undefined && held.packageId !== dep.packageId) {
        throw packageNameConflict(held, dep);
      }
      top.set(dep.packageName, dep);
    }
  }
}

/**
 * Make the PnP manifest for a step whose declared direct dependencies are
 * `directDeps`; only the packages among them have rows, not flags or loose
 * files.
 *
 * - The staged sources are the top-level row (`packageLocation: "./"`), which
 *   resolves exactly the direct packages.
 * - Where `self` is given, a further row under the sources' package name
 *   resolves the same names and that name too ({@link selfPackageRow}).
 * - Each package the direct ones reach has one row per name and reference
 *   ({@link referencesOf}), located at its tree in the pool, or at a virtual
 *   location where its content is wired more than one way ({@link locations}).
 *   Each row resolves the package's own name and its dependencies.
 * - The fallback pool is the top-level row's dependencies: a package from a
 *   repository that imports a name it does not declare (`reactcss` requires
 *   `react` without declaring it) resolves that name where the sources declare
 *   it, and only then. A package built in the project is in the fallback
 *   exclusion list instead, its row listing those same names after its own.
 *   PnpResolver gives the sources no fallback.
 * - `ignored`, a regular expression over paths relative to the table's root, is
 *   Yarn's `ignorePattern`: the files it names belong to no package of the
 *   table (a tree laid out for node's own resolution beside it).
 * - A package whose content hash is among `unplugged` is located at
 *   `node_modules/<name>/` in a tree it shares with the unplugged packages it is
 *   joined to by dependency edges ({@link unpluggedTreesOf}).
 *
 * Every list is sorted, so the manifest's bytes depend only on the graph.
 * Throws where two direct packages share a name ({@link assertOnePackagePerName}),
 * or two unplugged packages of one tree do.
 */
export function pnpManifestOf(
  directDeps: FileSet[],
  self?: ISelfPackage,
  ignored?: string,
  unplugged: ReadonlySet<string> = new Set(),
  { pool: poolDirectory = TREE_MOUNT, besideTable = false }: IPnpPlacement = {}
): IPnpManifest {
  assertOnePackagePerName(directDeps);
  const roots = directDeps.filter((dep): dep is PackageFileSet => dep instanceof PackageFileSet);
  const referenceIn = referencesOf(roots);
  const packages: PackageFileSet[] = [];
  const seen = new Set<string>();
  for (const pkg of reachablePackages(roots)) {
    /* One row per name and reference: two instances of one node share a row;
     * one package wired two ways is two nodes, so two rows. */
    const key = `${pkg.packageName}\0${referenceIn(pkg)}`;
    if (!seen.has(key)) {
      seen.add(key);
      packages.push(pkg);
    }
  }
  const isUnplugged = (pkg: PackageFileSet): boolean => unplugged.has(pkg.toManifestHash());
  const unpluggedTrees = unpluggedTreesOf(packages.filter(isUnplugged));
  /* With `besideTable`, the direct packages (by row) and the unplugged trees
   * holding one lie beside the table. */
  const rowOf = (pkg: PackageFileSet): string => `${pkg.packageName}\0${referenceIn(pkg)}`;
  const givenRows = new Set(besideTable ? roots.map(rowOf) : []);
  const isGiven = (pkg: PackageFileSet): boolean => givenRows.has(rowOf(pkg)) && !isUnplugged(pkg);
  const treesBeside = new Set(
    roots.filter(root => givenRows.has(rowOf(root)) && isUnplugged(root)).map(root => unpluggedTrees.get(root.toManifestHash())!)
  );
  const treeOf = (pkg: PackageFileSet): string => {
    const tree = unpluggedTrees.get(pkg.toManifestHash());
    if (tree !== undefined) {
      return treesBeside.has(tree)
        ? `node_modules/${pkg.packageName}`
        : `${poolDirectory}/${tree.toManifestHash()}/node_modules/${pkg.packageName}`;
    }
    return isGiven(pkg) ? `node_modules/${pkg.packageName}` : `${poolDirectory}/${pkg.toManifestHash()}`;
  };
  const trees = [
    ...packages.filter(pkg => !isUnplugged(pkg) && !isGiven(pkg)),
    ...[...new Set(unpluggedTrees.values())].filter(tree => !treesBeside.has(tree)),
  ];
  const beside = FileSet.unionAll(
    ...packages.filter(isGiven).map(pkg => pkg.mountedAt(`node_modules/${pkg.packageName}`)),
    ...treesBeside
  );
  const mountOf = locations(packages, referenceIn, treeOf);
  /* The one dependency list of both rows that stand for the sources, the
   * top-level row and the self row. Keep them one list: a source file matches
   * the self row (its location is the longer prefix), so a difference would
   * change what the sources resolve. */
  const topLevel = dependencyList(roots, referenceIn);
  /* The fallback pool is the top-level row's own dependencies, so a read set
   * names a fallback lookup by its top-level row (`<name> package.json`). */
  const pool = topLevel;
  /* Packages built in the project are excluded from the fallback; their rows
   * list the top-level dependencies instead (see packageInfo). */
  const excluded = packages.filter(pkg => !isResolved(pkg));
  const barred = new Set(excluded);
  /* Made last, as an excluded package's row needs the top-level dependencies. */
  const rows = new Map<string, Array<[string, IPnpPackageInfo]>>();
  for (const pkg of packages) {
    const reference = referenceIn(pkg);
    const existing = rows.get(pkg.packageName) ?? [];
    rows.set(pkg.packageName, existing);
    existing.push([reference, packageInfo(pkg, reference, mountOf(pkg), referenceIn, barred.has(pkg) ? topLevel : [])]);
  }
  const selfRow = self && selfPackageRow(self, topLevel);
  const state: IPnpSerializedState = {
    __info: INFO,
    /* No workspaces: the sources are the anonymous top-level package. */
    dependencyTreeRoots: [],
    enableTopLevelFallback: true,
    ignorePatternData: ignored ?? null,
    fallbackExclusionList: exclusionList(excluded, referenceIn),
    fallbackPool: pool,
    packageRegistryData: [
      [null, [[null, { packageLocation: "./", packageDependencies: topLevel, linkType: "SOFT" }]]],
      ...(selfRow ? [selfRow] : []),
      ...[...rows]
        .sort(byText(([name]) => name))
        .map(([name, versions]): [string, Array<[string | null, IPnpPackageInfo]>] => [
          name,
          [...versions].sort(byText(([reference]) => reference)),
        ]),
    ],
  };
  return { state, packages, trees, beside, mountOf, toFile: () => MemoryFile.from(serialize(state)) };
}

/** The file extension of a native addon. */
const NATIVE_ADDON = ".node";

/**
 * Find the packages to unplug among those `directDeps` reach: each that holds
 * a native addon (a `.node` file) or whose `package.json` sets
 * `preferUnplugged`. An addon finds the libraries it links against by paths
 * relative to itself, which assume its package and theirs lie side by side
 * under one `node_modules`.
 *
 * @return the content hashes of the packages to unplug.
 */
export function unpluggedPackages(directDeps: FileSet[]): Computable<ReadonlySet<string>> {
  const packages = reachablePackages(directDeps);
  return mapComputable(packages, pkg => (holdsNativeAddon(pkg) ? Computable.resolve(true) : prefersUnplugged(pkg))).then(
    wanted => new Set(packages.filter((_, index) => wanted[index]).map(pkg => pkg.toManifestHash()))
  );
}

/** @return true if `pkg` holds a native addon, otherwise false. */
function holdsNativeAddon(pkg: PackageFileSet): boolean {
  for (const [name] of pkg) {
    if (name.endsWith(NATIVE_ADDON)) {
      return true;
    }
  }
  return false;
}

/** @return true if `pkg`'s `package.json` sets `preferUnplugged`, otherwise
 *  false, as it is where the manifest is missing or unreadable. */
function prefersUnplugged(pkg: PackageFileSet): Computable<boolean> {
  return pkg
    .get("package.json")
    .then(file => (file === undefined ? false : readJsonFile(file, toJsonObject).then(json => json.preferUnplugged === true)))
    .catch(toleratingFailure(false));
}

/**
 * Make the trees the unplugged `packages` lie in: one for each group of them
 * joined by dependency edges, each package at `node_modules/<name>/` in its
 * group's tree, as an installed package is.
 *
 * @return each package's tree, by its content hash.
 * @throws where two packages of different content are unplugged under one name
 *   in one group.
 */
function unpluggedTreesOf(packages: ReadonlyArray<PackageFileSet>): Map<string, FileSet> {
  /* Each content hash's group, as a disjoint-set forest over the hashes. */
  const parent = new Map(packages.map((pkg): [string, string] => [pkg.toManifestHash(), pkg.toManifestHash()]));
  const root = (hash: string): string => {
    for (let at = hash; ;) {
      const up = parent.get(at)!;
      if (up === at) {
        return at;
      }
      at = up;
    }
  };
  for (const pkg of packages) {
    for (const dep of pkg.packages) {
      if (parent.has(dep.toManifestHash())) {
        parent.set(root(dep.toManifestHash()), root(pkg.toManifestHash()));
      }
    }
  }
  const groups = new Map<string, Map<string, PackageFileSet>>();
  for (const pkg of packages) {
    const group = groups.get(root(pkg.toManifestHash())) ?? new Map<string, PackageFileSet>();
    groups.set(root(pkg.toManifestHash()), group);
    const held = group.get(pkg.packageName);
    if (held !== undefined && held.toManifestHash() !== pkg.toManifestHash()) {
      throw new FabrError(
        `${held.packageId} and ${pkg.packageId} are unplugged together, and an unplugged tree lays out one package of each name`
      );
    }
    group.set(pkg.packageName, pkg);
  }
  const trees = new Map<string, FileSet>();
  for (const group of groups.values()) {
    const tree = FileSet.layout({ node_modules: [...group.values()].map(pkg => pkg.mountedAt(pkg.packageName)) });
    for (const pkg of group.values()) {
      trees.set(pkg.toManifestHash(), tree);
    }
  }
  return trees;
}

/**
 * Make the function naming each package's row reference in one manifest: the
 * hash of its name under {@link nodeNaming}, which gives each wiring of a
 * package id a reference of its own.
 */
function referencesOf(roots: ReadonlyArray<PackageFileSet>): (pkg: PackageFileSet) => string {
  const naming = nodeNaming(roots);
  const memo = new Map<PackageFileSet, string>();
  return pkg => {
    let reference = memo.get(pkg);
    if (reference === undefined) {
      reference = hashString(naming(pkg));
      memo.set(pkg, reference);
    }
    return reference;
  };
}

/**
 * Make the function locating each row's files: its directory (`treeOf`),
 * shared by every row there (the same package under two names) where they all
 * bind the same dependencies. Where one directory serves content wired more
 * than one way in this manifest, every wiring gets a virtual location of its
 * own over the directory ({@link virtualLocation}) and none uses the bare
 * directory: the resolver tells which row a file belongs to by its location.
 */
function locations(
  packages: ReadonlyArray<PackageFileSet>,
  referenceIn: (pkg: PackageFileSet) => string,
  treeOf: (pkg: PackageFileSet) => string
): (pkg: PackageFileSet) => string {
  const wiring = (pkg: PackageFileSet): string =>
    dependencyList(pkg.packages, referenceIn)
      .map(([name, reference]) => `${name}=${String(reference)}`)
      .join(",");
  const wiringsByDirectory = new Map<string, Set<string>>();
  for (const pkg of packages) {
    const held = wiringsByDirectory.get(treeOf(pkg)) ?? new Set<string>();
    held.add(wiring(pkg));
    wiringsByDirectory.set(treeOf(pkg), held);
  }
  return pkg =>
    (wiringsByDirectory.get(treeOf(pkg))?.size ?? 0) > 1
      ? virtualLocation(treeOf(pkg), hashString(wiring(pkg)).slice(0, 16))
      : treeOf(pkg);
}

/**
 * Make the row for sources that are a package, under the name they may import
 * themselves by: it resolves what the top-level row does and its own name, so
 * `pkg/sub` resolves to `<location>/sub` and bare `pkg` to the location's own
 * index. Its link type is `SOFT`, as the top-level row's is: it is a place in
 * the project, not a tree of the pool (PnpResolver.packageOf leaves it out).
 */
function selfPackageRow(
  self: ISelfPackage,
  topLevel: Array<[string, PnpDependencyTarget]>
): [string, Array<[string, IPnpPackageInfo]>] {
  return [
    self.name,
    [
      [
        SELF_REFERENCE,
        {
          packageLocation: self.location,
          packageDependencies: [[self.name, SELF_REFERENCE] as [string, PnpDependencyTarget], ...topLevel].sort(
            byText(([name]) => name)
          ),
          linkType: "SOFT",
        },
      ],
    ],
  ];
}

/** Each package's {@link referenceOf}, memoized per instance. */
const REFERENCES = new WeakMap<PackageFileSet, string>();

/**
 * Get a package's reference, its label in a table: the hash of its package
 * node's signature ({@link packageNodeSignature}: content hash, the ids its
 * dependencies are bound to, override flag). Two packages with the same bytes
 * have different references where they resolve differently (one package bound
 * to different versions of a requirement by different requirers), and so
 * separate rows.
 */
export function referenceOf(pkg: PackageFileSet): string {
  const known = REFERENCES.get(pkg);
  if (known !== undefined) {
    return known;
  }
  const reference = hashString(packageNodeSignature(pkg));
  REFERENCES.set(pkg, reference);
  return reference;
}

/**
 * Make one package's row: where its files are, and every name it may resolve,
 * its own included so it can import itself by name.
 *
 * `supplied` (the top-level row's dependencies, for a package excluded from the
 * fallback) is added after the package's own dependencies, which win on a
 * shared name. It lets a package built in the project resolve a name the
 * project supplies to every package, such as a node-builtin shim
 * (`@dep:path-browserify -> path`).
 */
function packageInfo(
  pkg: PackageFileSet,
  reference: string,
  location: string,
  referenceIn: (pkg: PackageFileSet) => string,
  supplied: ReadonlyArray<[string, PnpDependencyTarget]> = []
): IPnpPackageInfo {
  const own = new Map<string, PnpDependencyTarget>([[pkg.packageName, reference], ...dependencyList(pkg.packages, referenceIn)]);
  for (const [name, target] of supplied) {
    if (!own.has(name)) {
      own.set(name, target);
    }
  }
  return {
    /* Yarn's spelling: a location below the table's directory is `./`-prefixed,
     * one above it (the tree pool) is not. */
    packageLocation: `${location.startsWith("../") ? "" : "./"}${location}/`,
    packageDependencies: [...own].sort(byText(([name]) => name)),
    linkType: "HARD",
  };
}

/** @return true if a package came from a repository (its provenance has a
 * package-resolution step), otherwise false. */
function isResolved(pkg: PackageFileSet): boolean {
  for (let step = pkg.origin; step !== undefined; step = step.parent) {
    if (step.kind === PACKAGE_RESOLUTION_PROVENANCE) {
      return true;
    }
  }
  return false;
}

/** List the packages excluded from the fallback, in PnP's
 * `[name, [references]]` shape, sorted. */
function exclusionList(
  excluded: ReadonlyArray<PackageFileSet>,
  referenceIn: (pkg: PackageFileSet) => string
): Array<[string, string[]]> {
  const byName = new Map<string, string[]>();
  for (const pkg of excluded) {
    const held = byName.get(pkg.packageName) ?? [];
    byName.set(pkg.packageName, held);
    const reference = referenceIn(pkg);
    if (!held.includes(reference)) {
      held.push(reference);
    }
  }
  return [...byName].map(([name, references]): [string, string[]] => [name, [...references].sort()]).sort(byText(([name]) => name));
}

/** Write a package's dependencies as PnP dependency entries, sorted by name;
 * where one name repeats, the first is taken. */
function dependencyList(
  deps: ReadonlyArray<PackageFileSet>,
  referenceIn: (pkg: PackageFileSet) => string
): Array<[string, PnpDependencyTarget]> {
  const entries = new Map<string, PnpDependencyTarget>();
  for (const dep of deps) {
    if (!entries.has(dep.packageName)) {
      entries.set(dep.packageName, referenceIn(dep));
    }
  }
  return [...entries].sort(byText(([name]) => name));
}

/**
 * Locate a package's tree, relative to the working directory: under the pool
 * mount, named by the package's content digest, as {@link BuildCache.ensureTree}
 * names it.
 */
export function treeMountOf(pkg: PackageFileSet): string {
  return `${TREE_MOUNT}/${pkg.toManifestHash()}`;
}

/** Make an ascending comparator over a text projection, by code unit. */
function byText<T>(of: (value: T) => string): (a: T, b: T) => number {
  return (a, b) => (of(a) < of(b) ? -1 : of(a) > of(b) ? 1 : 0);
}

/** Serialize the manifest as two-space JSON, newline-terminated, as Yarn writes it. */
function serialize(state: IPnpSerializedState): string {
  return `${JSON.stringify(state, undefined, 2)}\n`;
}
